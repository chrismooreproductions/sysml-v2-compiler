// Package gen turns the SysML.ecore metamodel into the Go source of the
// schema package's data tables.
package gen

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

const xsi = "http://www.w3.org/2001/XMLSchema-instance"

type ePackage struct {
	Classifiers []eClassifier `xml:"eClassifiers"`
}

type eClassifier struct {
	Type      string     `xml:"http://www.w3.org/2001/XMLSchema-instance type,attr"`
	Name      string     `xml:"name,attr"`
	Supers    string     `xml:"eSuperTypes,attr"`
	Abstract  string     `xml:"abstract,attr"`
	Interface string     `xml:"interface,attr"`
	Features  []eFeature `xml:"eStructuralFeatures"`
	Literals  []eLiteral `xml:"eLiterals"`
}

type eFeature struct {
	Type        string        `xml:"http://www.w3.org/2001/XMLSchema-instance type,attr"`
	Name        string        `xml:"name,attr"`
	EType       string        `xml:"eType,attr"`
	Lower       string        `xml:"lowerBound,attr"`
	Upper       string        `xml:"upperBound,attr"`
	Ordered     string        `xml:"ordered,attr"`
	Derived     string        `xml:"derived,attr"`
	Transient   string        `xml:"transient,attr"`
	Volatile    string        `xml:"volatile,attr"`
	Containment string        `xml:"containment,attr"`
	Opposite    string        `xml:"eOpposite,attr"`
	Default     string        `xml:"defaultValueLiteral,attr"`
	Annotations []eAnnotation `xml:"eAnnotations"`
}

type eAnnotation struct {
	Source     string `xml:"source,attr"`
	References string `xml:"references,attr"`
}

type eLiteral struct {
	Name    string `xml:"name,attr"`
	Value   string `xml:"value,attr"`
	Literal string `xml:"literal,attr"`
}

// ref turns an ecore reference such as "#//Subsetting/subsettedFeature" into
// "Subsetting.subsettedFeature", and "#//Element" into "Element".
func ref(s string) string {
	if i := strings.Index(s, "#//"); i >= 0 {
		s = s[i+3:]
	}
	return strings.ReplaceAll(s, "/", ".")
}

func refs(s string) []string {
	var out []string
	for _, f := range strings.Fields(s) {
		out = append(out, ref(f))
	}
	return out
}

// Generate returns the Go source for the schema tables of an ecore document.
func Generate(ecore []byte) ([]byte, error) {
	var pkg ePackage
	if err := xml.Unmarshal(ecore, &pkg); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genschema from SysML.ecore; DO NOT EDIT.\n\n")
	b.WriteString("// SPDX-License-Identifier: EPL-2.0\n\n")
	b.WriteString("package schema\n\n")

	b.WriteString("var classes = []Class{\n")
	for _, c := range pkg.Classifiers {
		if c.Type != "ecore:EClass" {
			continue
		}
		fmt.Fprintf(&b, "\t{Name: %q, Abstract: %t, Interface: %t, Supers: %s, Features: []Feature{\n",
			c.Name, c.Abstract == "true", c.Interface == "true", strs(refs(c.Supers)))
		for _, f := range c.Features {
			lower := 0
			if f.Lower != "" {
				lower, _ = strconv.Atoi(f.Lower)
			}
			many := f.Upper != "" && f.Upper != "1"
			var redefines, subsets []string
			union := false
			for _, a := range f.Annotations {
				switch a.Source {
				case "redefines":
					redefines = append(redefines, refs(a.References)...)
				case "subsets":
					subsets = append(subsets, refs(a.References)...)
				case "union":
					union = true
				}
			}
			fmt.Fprintf(&b, "\t\t{Name: %q, Type: %q, Attribute: %t, Lower: %d, Many: %t, Containment: %t, Derived: %t, Transient: %t, Volatile: %t, Union: %t, Default: %q, Opposite: %q, Redefines: %s, Subsets: %s},\n",
				f.Name, typeName(f.EType), f.Type == "ecore:EAttribute", lower, many, f.Containment == "true",
				f.Derived == "true", f.Transient == "true", f.Volatile == "true", union,
				f.Default, ref(f.Opposite), strs(redefines), strs(subsets))
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n\nvar enums = []Enum{\n")
	for _, c := range pkg.Classifiers {
		if c.Type != "ecore:EEnum" {
			continue
		}
		fmt.Fprintf(&b, "\t{Name: %q, Literals: []Literal{\n", c.Name)
		for i, l := range c.Literals {
			value := i
			if l.Value != "" {
				value, _ = strconv.Atoi(l.Value)
			}
			lit := l.Literal
			if lit == "" {
				lit = l.Name
			}
			fmt.Fprintf(&b, "\t\t{Name: %q, Value: %d, Literal: %q},\n", l.Name, value, lit)
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// typeName is the simple name of a feature's type: "#//Element" and
// "ecore:EDataType http://www.eclipse.org/emf/2002/Ecore#//EString" give
// Element and EString.
func typeName(s string) string {
	s = ref(s)
	if i := strings.LastIndex(s, "."); i >= 0 {
		s = s[i+1:]
	}
	return s
}

func strs(in []string) string {
	if len(in) == 0 {
		return "nil"
	}
	var parts []string
	for _, s := range in {
		parts = append(parts, strconv.Quote(s))
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}
