// Package gen turns the pilot implementation's ImplicitGeneralizationMap into
// the Go table of default supertypes that the semantics package uses.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
)

var putRe = regexp.MustCompile(`put\((\w+)Impl\.class,\s*"(\w+)",\s*"([^"]+)"\)`)

// Generate returns Go source for the table in a copy of
// ImplicitGeneralizationMap.java: for each metaclass and kind, the qualified
// name of the library type it implicitly specializes.
func Generate(java []byte) ([]byte, error) {
	matches := putRe.FindAllSubmatch(java, -1)
	if len(matches) < 100 {
		return nil, fmt.Errorf("found only %d entries; is this ImplicitGeneralizationMap.java?", len(matches))
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genimplicit from upstream/ImplicitGeneralizationMap.java.txt; DO NOT EDIT.\n\n")
	b.WriteString("// SPDX-License-Identifier: EPL-2.0\n\n")
	b.WriteString("package semantics\n\n")
	b.WriteString("// implicitTable maps \"Metaclass_kind\" to the library type that metaclass implicitly\n")
	b.WriteString("// specializes for that kind of specialization. Each entry is the data behind one of\n")
	b.WriteString("// the specification's check<Class>Specialization validation constraints.\n")
	b.WriteString("var implicitTable = map[string]string{\n")
	for _, m := range matches {
		fmt.Fprintf(&b, "\t%q: %q,\n", string(m[1])+"_"+string(m[2]), string(m[3]))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
