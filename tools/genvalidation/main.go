// This file reads the pilot implementation's Xtend validators
// (org.omg.sysml.xtext SysMLValidator.xtend, org.omg.kerml.xtext
// KerMLValidator.xtend) to take the messages of their checks.

// Command genvalidation writes internal/semantics/validation_messages_gen.go
// from the pilot implementation's validators: the message of each constraint,
// by its constant's name.
//
//	go run ./tools/genvalidation <pilot checkout> > internal/semantics/validation_messages_gen.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var decl = regexp.MustCompile(`public static val (INVALID_\w+?)(_MSG(?:_\d+)?)?\s*=\s*(?:"([^"]*)"|'([^']*)')`)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genvalidation <pilot checkout>")
		os.Exit(2)
	}
	files := []string{
		"org.omg.kerml.xtext/src/org/omg/kerml/xtext/validation/KerMLValidator.xtend",
		"org.omg.sysml.xtext/src/org/omg/sysml/xtext/validation/SysMLValidator.xtend",
	}
	msgs := map[string]string{} // constant name without INVALID_ -> message
	for _, f := range files {
		b, err := os.ReadFile(filepath.Join(os.Args[1], f))
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		for _, m := range decl.FindAllStringSubmatch(string(b), -1) {
			if m[2] == "_MSG" {
				msg := m[3]
				if msg == "" {
					msg = m[4]
				}
				msgs[strings.TrimPrefix(m[1], "INVALID_")] = msg
			}
		}
	}
	var names []string
	for n := range msgs {
		names = append(names, n)
	}
	sort.Strings(names)
	var out bytes.Buffer
	out.WriteString("// Code generated by tools/genvalidation; DO NOT EDIT.\n// SPDX-License-Identifier: EPL-2.0\n\npackage semantics\n\n")
	out.WriteString("// validationMessages maps a constraint, by the pilot's constant name without INVALID_, to its message.\nvar validationMessages = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&out, "\t%q: %q,\n", n, msgs[n])
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(src)
}
